const dropdown = document.querySelector(".lang-dropdown");
const langBtn = document.getElementById("langBtn");
const currentFlag = document.getElementById("currentFlag");
const currentLang = document.getElementById("currentLang");
const langOptions = document.querySelectorAll(".lang-option");

function getGithubBadgeUrl(label) {
    const formatted = encodeURIComponent(label.trim().replace(/\s+/g, "_"));
    return `https://img.shields.io/badge/GitHub-${formatted}-181717?style=for-the-badge&logo=github`;
}

function updateTranslations(dict) {
    document.querySelectorAll("[data-i18n]").forEach((el) => {
        const key = el.dataset.i18n;
        if (dict[key]) el.textContent = dict[key];
    });

    document.querySelectorAll("[data-i18n-aria-label]").forEach((el) => {
        const key = el.dataset.i18nAriaLabel;
        if (dict[key]) el.setAttribute("aria-label", dict[key]);
    });

    document.querySelectorAll("[data-i18n-badge]").forEach((img) => {
        const key = img.dataset.i18nBadge;
        if (dict[key]) {
            img.src = getGithubBadgeUrl(dict[key]);
            img.alt = dict[key];
        }
    });

    document.querySelectorAll("[data-i18n-attr]").forEach((el) => {
        el.dataset.i18nAttr.split(",").forEach((pair) => {
            const [attr, key] = pair.split(":").map((s) => s.trim());
            if (attr && key && dict[key]) {
                el.setAttribute(attr, dict[key]);
            }
        });
    });
}

function setLanguage(lang) {
    const dict = translations[lang] || translations.en;

    document.documentElement.lang = lang;
    if (currentFlag) currentFlag.textContent = dict.flag;
    if (currentLang) currentLang.textContent = dict.code;

    updateTranslations(dict);

    langOptions.forEach((btn) => {
        const isSelected = btn.dataset.lang === lang;
        btn.classList.toggle("active", isSelected);
        btn.setAttribute("aria-selected", String(isSelected));
    });

    localStorage.setItem("acUraniumLang", lang);
}

function setDropdownOpen(open) {
    if (!dropdown || !langBtn) return;
    dropdown.classList.toggle("open", open);
    langBtn.setAttribute("aria-expanded", String(open));
}

function closeDropdown() {
    setDropdownOpen(false);
}

if (langBtn && dropdown) {
    langBtn.addEventListener("click", (e) => {
        e.stopPropagation();
        setDropdownOpen(!dropdown.classList.contains("open"));
    });

    langOptions.forEach((btn) => {
        btn.addEventListener("click", () => {
            setLanguage(btn.dataset.lang);
            closeDropdown();
        });
    });

    document.addEventListener("click", (e) => {
        if (!dropdown.contains(e.target)) {
            closeDropdown();
        }
    });
}

document.addEventListener("keydown", (e) => {
    if (e.key === "Escape") {
        closeDropdown();
    }
});

